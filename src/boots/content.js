export function sizeForFoot(cm) {
  if (!Number.isFinite(cm) || cm < 22 || cm > 33) return { kind: "invalid" };
  if (cm < 24.9) return { kind: "small" };
  const row = FOOT_CHART.find(([, max]) => cm <= max);
  return row ? { kind: "ok", size: row[0] } : { kind: "large" };
}

